"""Pixel-art cursors in the game's style: off-white fill, dark teal outline, hard drop shadow.

Each cursor is a 16x16 sprite ("#" outline, "s" fill, "d" shade, "r"/"R"/"o" pencil colours); a
shadow is added one pixel down-right, then the sprite is scaled x2 with nearest neighbour (32x32
is the largest size every browser/OS accepts without falling back).

    python scripts/make-cursors.py  ->  public/cursors/*.png
"""

