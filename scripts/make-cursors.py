def build(sprite: str) -> Image.Image:
    rows = [r.ljust(16, ".") for r in sprite.strip("\n").split("\n")]
    h, w = len(rows), 16
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = img.load()
    colors = {"#": OUTLINE, "s": FILL, "d": SHADE, "r": ACCENT, "R": ACCENT_DARK, "o": WOOD}
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in colors:
                px[x, y] = colors[ch]
    # hard shadow one sprite pixel down-right, under everything opaque
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    opx = out.load()
    for y in range(h):
        for x in range(w):
            if px[x, y][3] and x + 1 < w and y + 1 < h:
                opx[x + 1, y + 1] = SHADOW
    out.alpha_composite(img)
    return out.resize((w * SCALE, h * SCALE), Image.NEAREST)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (hot, sprite) in CURSORS.items():
        build(sprite).save(OUT / f"{name}.png")
        print(f"{name}.png hotspot {hot[0] * SCALE} {hot[1] * SCALE}")


if __name__ == "__main__":
    main()
